import dotenv from "dotenv";
import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
dotenv.config({ path: [".env.local", ".env"], quiet: true });
const { prisma } = await import("../server/utils/prisma.js");
const { handleCustomerMessage } = await import("../server/chatbot/handler.js");
const { getSettings } = await import("../server/chatbot/settings.js");
const { rateLimit, hash } = await import("../server/chatbot/security.js");
const settings = await getSettings();
const created = [];
const originalFetch = globalThis.fetch;
const originalKey = process.env.OPENAI_API_KEY;
const originalSettingsRead = prisma.chatSettings.upsert.bind(prisma.chatSettings);
const originalCatalogueRead = prisma.food.findMany.bind(prisma.food);
const rateKey = `qa-rate-${randomUUID()}`;
async function conversation(locale = "en") {
  const c = await prisma.chatConversation.create({ data: { channel: "test", tokenHash: randomUUID(), locale } });
  created.push(c.id); return c;
}
const send = (c, text, id = randomUUID()) => handleCustomerMessage({ conversationId: c.id, text, clientMessageId: id });
try {
  let c = await conversation();
  delete process.env.OPENAI_API_KEY;
  let result = await send(c, "What products do you sell?");
  assert.ok(result.reply?.text); assert.ok(result.paused);
  assert.ok(result.reply.text.includes("contact our team"));
  assert.equal(await prisma.chatLead.count({ where: { conversationId: c.id } }), 1);
  await send(c, "My name is Test Person. Phone 00000001");
  const lead = await prisma.chatLead.findFirst({ where: { conversationId: c.id } });
  assert.equal(lead.phone, "00000001"); assert.equal(lead.name, "Test Person");
  process.env.OPENAI_API_KEY = originalKey;
  c = await conversation();
  globalThis.fetch = (url, options) => String(url).startsWith("https://api.openai.com/") ? Promise.resolve(new Response("", { status: 500 })) : originalFetch(url, options);
  result = await send(c, "What does delivery cost?");
  assert.ok(result.reply?.text); assert.ok(result.paused);
  globalThis.fetch = originalFetch;
  c = await conversation();
  // Stub this process's settings read only; never toggle the live production setting.
  prisma.chatSettings.upsert = async () => ({ ...settings, enabled: false });
  result = await send(c, "Hello");
  assert.equal(result.reply, null); assert.ok(result.paused);
  assert.equal(await prisma.chatMessage.count({ where: { conversationId: c.id, role: "assistant" } }), 0);
  prisma.chatSettings.upsert = originalSettingsRead;
  c = await conversation();
  await prisma.chatConversation.update({ where: { id: c.id }, data: { leaseUntil: new Date(Date.now() + 25_000), leaseOwner: "fake-lease" } });
  await assert.rejects(send(c, "Hello"), { code: "CONVERSATION_BUSY" });
  await prisma.chatConversation.update({ where: { id: c.id }, data: { leaseUntil: null, leaseOwner: null } });
  const replayId = randomUUID();
  await prisma.chatMessage.create({ data: { conversationId: c.id, role: "customer", text: "Hello", clientMessageId: replayId } });
  result = await send(c, "Hello", replayId);
  assert.ok(result.reply?.metadata?.verified);
  assert.equal(await prisma.chatMessage.count({ where: { conversationId: c.id, role: "customer" } }), 1);
  await assert.rejects(send(c, "A different message", replayId), { code: "MESSAGE_ID_REUSED" });
  c = await conversation("mn");
  const product = await prisma.food.findFirstOrThrow();
  result = await send(c, `${product.foodName} үнэ хэд вэ?`);
  assert.ok(result.reply.metadata.productIds.includes(product.id));
  result = await send(c, "Тэр нь ямар хэмжээтэй вэ?");
  assert.ok(result.reply.metadata.intents.includes("sizes"));
  assert.ok(result.reply.metadata.productIds.includes(product.id));
  await rateLimit(rateKey, 2, 3600000);
  await rateLimit(rateKey, 2, 3600000);
  await assert.rejects(rateLimit(rateKey, 2, 3600000), { code: "RATE_LIMITED" });
  c = await conversation();
  let reads = 0;
  // A fake in-process catalogue changes during understanding; no live product is modified.
  prisma.food.findMany = async () => [{ id: "fake-fresh", foodName: "Test Serum Fresh", ingredients: "Test description", price: ++reads === 1 ? 1000 : 2000, sizes: [{ label: "Test size", stock: reads === 1 ? 1 : 10 }] }];
  globalThis.fetch = (url, options) => String(url).startsWith("https://api.openai.com/") ? Promise.resolve(new Response(JSON.stringify({ choices: [{ finish_reason: "stop", message: { content: JSON.stringify({ intents: ["price"], productIds: ["fake-fresh"], faqIndexes: [], locale: "en", orderNumber: "", phone: "", name: "" }) } }], usage: { total_tokens: 1 } }), { status: 200, headers: { "Content-Type": "application/json" } })) : originalFetch(url, options);
  result = await send(c, "What is the price of Test Serum Fresh?");
  assert.ok(result.reply.text.includes("2,000₮"));
  assert.ok(!result.reply.text.includes("1,000₮"));
  assert.ok(result.reply.text.includes("Test size · Available"));
  assert.ok(!result.reply.text.includes("Almost gone"));
  c = await conversation();
  globalThis.fetch = async (url, options) => {
    if (!String(url).startsWith("https://api.openai.com/")) return originalFetch(url, options);
    const current = await prisma.chatConversation.findUniqueOrThrow({ where: { id: c.id } });
    await prisma.chatConversation.update({ where: { id: c.id }, data: { paused: true, state: { ...current.state, humanTakeoverAt: new Date().toISOString() } } });
    return new Response(JSON.stringify({ choices: [{ finish_reason: "stop", message: { content: JSON.stringify({ intents: ["unknown"], productIds: [], faqIndexes: [], locale: "en", orderNumber: "", phone: "", name: "" }) } }] }), { status: 200, headers: { "Content-Type": "application/json" } });
  };
  result = await send(c, "An unsupported question");
  assert.equal(result.reply, null, "Taking over during provider work must suppress even a handoff reply");
  assert.ok((await prisma.chatConversation.findUniqueOrThrow({ where: { id: c.id } })).state.humanTakeoverAt);
  console.log("Fallbacks, leads, kill switch, lease/retry, memory, DB limits, fresh facts and takeover during provider work: PASS");
} finally {
  globalThis.fetch = originalFetch;
  prisma.chatSettings.upsert = originalSettingsRead;
  prisma.food.findMany = originalCatalogueRead;
  if (originalKey === undefined) delete process.env.OPENAI_API_KEY; else process.env.OPENAI_API_KEY = originalKey;
  await prisma.chatRateBucket.deleteMany({ where: { key: { startsWith: `${hash(rateKey)}:` } } });
  await prisma.chatErrorLog.deleteMany({ where: { conversationId: { in: created } } });
  await prisma.chatConversation.deleteMany({ where: { id: { in: created }, channel: "test" } });
  await prisma.$disconnect();
}
