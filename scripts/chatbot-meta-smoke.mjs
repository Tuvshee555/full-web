import dotenv from "dotenv";
import assert from "node:assert/strict";
import { createHmac, randomInt } from "node:crypto";
dotenv.config({ path: [".env.local", ".env"], quiet: true });
process.env.META_PAGE_ACCESS_TOKEN = "fake-token";
process.env.META_APP_SECRET = "fake-secret";
process.env.META_VERIFY_TOKEN = "fake-verification";
delete process.env.TELEGRAM_BOT_TOKEN; delete process.env.TELEGRAM_CHAT_ID;
const { default: express } = await import("express");
const { metaRouter } = await import("../server/chatbot/meta.js");
const { prisma } = await import("../server/utils/prisma.js");
const { getSettings } = await import("../server/chatbot/settings.js");
assert.equal((await getSettings()).metaOutbound, false, "Run fake Meta QA with outbound disabled");
const app = express();
app.use(express.json({ limit: "4mb", verify: (req, res, bytes) => { req.rawBody = bytes; } }));
app.use("/webhooks", metaRouter);
const server = app.listen(0, "127.0.0.1");
await new Promise((resolve) => server.once("listening", resolve));
const base = `http://127.0.0.1:${server.address().port}/webhooks`;
const page = String(randomInt(100000000, 999999999));
const sender = String(randomInt(100000000, 999999999));
const created = [];
try {
  for (const channel of ["messenger", "instagram"]) {
    const url = `${base}/${channel}`;
    assert.equal((await fetch(url + "?hub.mode=subscribe&hub.verify_token=fake-verification&hub.challenge=12345")).status, 200);
    assert.equal(await (await fetch(url + "?hub.mode=subscribe&hub.verify_token=fake-verification&hub.challenge=12345")).text(), "12345");
    assert.equal((await fetch(url + "?hub.mode=subscribe&hub.verify_token=wrong&hub.challenge=12345")).status, 403);
    const body = JSON.stringify({ object: channel === "instagram" ? "instagram" : "page", entry: [{ id: page, messaging: [{ sender: { id: sender }, recipient: { id: page }, message: { mid: `fake-${channel}-${page}`, text: "I want a human" } }] }] });
    const signature = `sha256=${createHmac("sha256", "fake-secret").update(body).digest("hex")}`;
    assert.equal((await fetch(url, { method: "POST", headers: { "Content-Type": "application/json" }, body })).status, 403);
    const headers = { "Content-Type": "application/json", "X-Hub-Signature-256": signature };
    assert.equal((await fetch(url, { method: "POST", headers, body: body + " " })).status, 403);
    for (let n = 0; n < 2; n++) assert.equal((await fetch(url, { method: "POST", headers, body })).status, 200);
    const c = await prisma.chatConversation.findUniqueOrThrow({ where: { channel_externalId: { channel, externalId: `${page}:${sender}` } } });
    created.push(c.id);
    assert.equal(await prisma.chatMessage.count({ where: { conversationId: c.id, role: "customer" } }), 1);
    assert.equal(await prisma.chatLead.count({ where: { conversationId: c.id } }), 1);
    assert.equal((await prisma.chatMessage.findFirst({ where: { conversationId: c.id, role: "assistant" } })).deliveryStatus, "suppressed");
    assert.ok(c.paused);
  }
  delete process.env.META_VERIFY_TOKEN;
  assert.equal((await fetch(base + "/messenger")).status, 503);
  console.log("Fake Messenger + Instagram handshake, raw HMAC, persistent dedup, handoff and outbound-off: PASS");
} finally {
  // Only the fake Page/sender generated by this process can be cleaned up.
  const own = await prisma.chatConversation.findMany({ where: { channel: { in: ["messenger", "instagram"] }, externalId: `${page}:${sender}` }, select: { id: true } });
  const ids = own.map((c) => c.id);
  await prisma.chatErrorLog.deleteMany({ where: { conversationId: { in: ids } } });
  await prisma.chatConversation.deleteMany({ where: { id: { in: ids } } });
  await new Promise((resolve) => server.close(resolve));
  await prisma.$disconnect();
}
